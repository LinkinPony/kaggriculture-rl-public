"""Validated Hydra settings for teacher-data generation."""

from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field, model_validator


class SubmissionArtifactSettings(BaseModel):
    """Immutable identity of the Kaggle submission used as the teacher."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    submission_id: int = Field(gt=0)
    archive_path: Path
    archive_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    source_commit: str = Field(pattern=r"^[0-9a-f]{40}$")
    route_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")


class TeacherDataSettings(BaseModel):
    """One immutable rollout dataset generated by the authenticated teacher."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    teacher: SubmissionArtifactSettings
    output_dir: Path
    report_dir: Path
    seed_start: int = Field(ge=0)
    games: int = Field(ge=3)
    games_per_shard: int = Field(gt=0)
    workers: int = Field(gt=0)
    policy_workers: int = Field(gt=0, le=256)
    compression_level: int = Field(ge=0, le=9)
    unit_limit: int = Field(gt=0, le=255)
    environment: dict[str, object]

    @model_validator(mode="after")
    def validate_generation(self) -> TeacherDataSettings:
        """Reject seed ranges and environments outside the numeric actor ABI."""
        if self.seed_start + self.games - 1 > 2**63 - 1:
            raise ValueError("teacher rollout seed range exceeds the native int64 ABI")
        episode_steps = self.environment.get("episodeSteps")
        market_orders = self.environment.get("maxMarketOrdersPerTurn")
        if not isinstance(episode_steps, int) or isinstance(episode_steps, bool):
            raise ValueError("environment episodeSteps must be an integer")
        if episode_steps < 2:
            raise ValueError("environment episodeSteps must allow a transition")
        if not isinstance(market_orders, int) or isinstance(market_orders, bool):
            raise ValueError("environment maxMarketOrdersPerTurn must be an integer")
        if market_orders < 1:
            raise ValueError("environment maxMarketOrdersPerTurn must be positive")
        return self


class TeacherDataAppSettings(BaseModel):
    """Hydra root for authenticated teacher rollout generation."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    teacher_data: TeacherDataSettings


__all__ = [
    "SubmissionArtifactSettings",
    "TeacherDataAppSettings",
    "TeacherDataSettings",
]
