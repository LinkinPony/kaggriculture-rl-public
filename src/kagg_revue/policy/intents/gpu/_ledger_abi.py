def _gather_rows(values: Tensor, indices: Tensor) -> Tensor:
    """Gather one scalar from every batch row."""
    return values.gather(1, indices[:, None]).squeeze(1)


def _replace_rows(target: Tensor, source: Tensor, rows: Tensor) -> Tensor:
    """Replace rows selected by a batch mask without an in-place alias."""
    shape = (rows.shape[0],) + (1,) * (target.ndim - 1)
    return torch.where(rows.view(shape), source, target)
